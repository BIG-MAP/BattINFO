// Build-time template sync — vendored-with-sync, like sync-schemas.mjs.
//
// A template is a starting point, not a record: the package's own template_*
// builders describe them as "starter documents for hand-edited drafts". The
// curated research examples are exactly that -- one per cell format, already
// valid, already reviewed -- so they are the templates rather than a set
// invented here.
//
// The examples are copied verbatim, minted IRI and all. What turns one into a
// template -- dropping that identity and, of the provenance, everything but the
// kind of source -- is `asTemplate` in app/create/load.ts, applied when a
// template is chosen. scripts/check-create.ts fails the build if a template
// could reach the form still carrying either.
//
//   Run:   npm run sync:templates
//   CI:    npm run sync:templates -- --check   (fails on drift)
//
// No dependencies; Node ESM only.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..");
const EXAMPLES = resolve(repoRoot, "src", "battinfo", "data", "examples", "cell-spec");
const SOURCE = resolve(EXAMPLES, "research");
const OUT = resolve(here, "..", "lib", "templates.generated.ts");

// Linked example records that are templates too. A cell spec other records
// point at lives in cell-spec/ rather than research/, where the reference
// lookup finds it, so it is named here: slug -> file.
const LINKED = {
  "empa-coin-cell": "cell-spec-5hy0-g0f7-bxzz-tmtm.json",
};

const sources = [
  ...readdirSync(SOURCE)
    .filter((name) => name.endsWith(".json"))
    .map((name) => [name.replace(/\.example\.json$|\.json$/, ""), resolve(SOURCE, name)]),
  ...Object.entries(LINKED).map(([slug, name]) => [slug, resolve(EXAMPLES, name)]),
];

const templates = sources
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([slug, path]) => {
    const record = JSON.parse(readFileSync(path, "utf-8"));
    return { slug, format: record.cell_spec?.cell_format ?? "unknown", record };
  });

const body =
  `// GENERATED by scripts/sync-templates.mjs — do not edit.\n` +
  `// Source of truth: src/battinfo/data/examples/cell-spec/research/ and LINKED (${templates.length} templates).\n` +
  `// Copied verbatim; app/create/load.ts strips what makes one a template.\n` +
  `// Regenerate with \`npm run sync:templates\`; CI fails if this file drifts.\n\n` +
  `export const TEMPLATES: { slug: string; format: string; record: Record<string, unknown> }[] = ` +
  JSON.stringify(templates, null, 2) +
  ";\n";

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf-8") : "";
  if (current.replace(/\r\n/g, "\n") !== body.replace(/\r\n/g, "\n")) {
    console.error(
      "lib/templates.generated.ts drifts from its example records.\n" +
        "Run `npm run sync:templates` in web/ and commit the result.",
    );
    process.exit(1);
  }
  console.log(`templates in sync (${templates.length}).`);
} else {
  writeFileSync(OUT, body);
  console.log(`Wrote ${OUT} (${templates.length} templates).`);
}
