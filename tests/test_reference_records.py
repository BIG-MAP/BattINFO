"""The committed reference-records chapter must match what the library does today.

docs/records/ is generated by scripts/gen_reference_records.py: each
page's authoring snippet is executed against the current library, the record it
produces is validated under the strict policy, and the emitted JSON-LD is
committed beside it. This test regenerates the chapter in memory and fails on
drift — a schema, API, or emitter change that alters any reference record must
regenerate the chapter in the same PR:

    uv run python scripts/gen_reference_records.py
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

_spec = importlib.util.spec_from_file_location("gen_reference_records", ROOT / "scripts" / "gen_reference_records.py")
assert _spec is not None and _spec.loader is not None
gen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gen)


def test_reference_records_match_the_current_library() -> None:
    expected = gen.render_all()
    for name, text in expected.items():
        path = gen.OUT_DIR / name
        assert path.exists(), (
            f"docs/records/{name} is missing — "
            "run `uv run python scripts/gen_reference_records.py` and commit the result"
        )
        actual = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        assert actual == text.replace("\r\n", "\n"), (
            f"docs/records/{name} drifts from what the current library "
            "produces — run `uv run python scripts/gen_reference_records.py` and "
            "review the diff: it is the propagation record of your change"
        )


def test_generation_is_deterministic() -> None:
    # Two builds in one process must agree byte-for-byte; a snippet that lets a
    # randomly minted uid or a wall-clock timestamp leak through would make the
    # drift gate flaky instead of honest.
    assert gen.render_all() == gen.render_all()


def test_the_pages_say_where_voltage_reference_goes() -> None:
    # The emitters put a voltage_reference on a quantity under
    # schema:valueReference, never under hasMetrologicalReference (the unit
    # already fills EMMO's one metrological reference). The pages said the
    # opposite.
    from battinfo.jsonld import test_to_jsonld
    from battinfo.transform.json_to_jsonld import _descriptor_quantity_node

    li = {"value_text": "Li/Li+"}
    quantity = _descriptor_quantity_node(
        "average_voltage", {"value": 3.7, "unit": "V", "conditions": {"voltage_reference": li}}
    )
    assert quantity is not None
    assert quantity["schema:valueReference"]["@type"] == ["ReferenceElectrode", "LithiumElectrode"]
    test_node = test_to_jsonld(
        {"test": {"id": "https://w3id.org/battinfo/test/0000-0000-0000-0000", "conditions": {"voltage_reference": li}}}
    )
    test_body = {key: value for key, value in test_node.items() if key != "@context"}
    assert "voltage_reference" in str(test_body)
    assert "hasMetrologicalReference" not in str(quantity) + str(test_body)

    for name, text in gen.render_all().items():
        assert "hasMetrologicalReference" not in text, f"docs/records/{name} names hasMetrologicalReference"
    intro = gen.render_all()["cells.md"].split("## Fields", 1)[1]
    assert "`voltage_reference` key goes under `schema:valueReference`" in intro


def test_the_schemas_say_where_voltage_reference_goes() -> None:
    # The conditions description in the JSON Schemas (and every copy of them
    # that ships or is hosted) made the same hasMetrologicalReference claim.
    root = Path(__file__).resolve().parents[1]
    paths = [
        *sorted((root / "assets" / "schemas").rglob("*.json")),
        *sorted((root / "src" / "battinfo" / "data" / "schemas").rglob("*.json")),
        *sorted((root / "src" / "battinfo" / "data" / "profiles").rglob("*.json")),
        root / "web" / "lib" / "schemas.generated.ts",
    ]
    for path in paths:
        text = path.read_text(encoding="utf-8")
        assert "hasMetrologicalReference" not in text, path.relative_to(root).as_posix()
    quantity = (root / "assets" / "schemas" / "modules" / "common" / "quantity.schema.json").read_text(encoding="utf-8")
    assert "The voltage_reference key emits under schema:valueReference" in quantity
