"""Generate the property & unit reference page from the curated mapping tables.

These tables are the single source of truth for how `properties={...}` keys
and unit symbols become EMMO IRIs in the emitted JSON-LD. Committed output;
tests/test_generated_reference.py regenerates in memory and fails on drift.

Usage:
    uv run python scripts/gen_property_reference.py
"""

from __future__ import annotations

import json
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAPPINGS = ROOT / "assets" / "mappings" / "domain-battery"
OUT = ROOT / "docs" / "pages" / "property-reference.md"
CONTEXT = ROOT / "src" / "battinfo" / "data" / "context" / "domain-battery.context.json"
PARAMETERS = ROOT / "src" / "battinfo" / "data" / "vocab" / "parameters.json"
CELL_SCHEMA = ROOT / "assets" / "schemas" / "cell-canonical.schema.json"


def parameter_only_keys() -> dict[str, dict]:
    """Parameter-vocabulary keys that are claims only, never a cell spec's properties.

    A key counts when a cell spec does not accept it and the vocabulary
    scopes it to the cell or state parts of a parameter file only (a BPX
    file's Cell and State values, such as the electrode pair count or the
    initial state of charge).
    """
    vocab = json.loads(PARAMETERS.read_text(encoding="utf-8"))["parameters"]
    spec_set = json.loads(CELL_SCHEMA.read_text(encoding="utf-8"))["$defs"]["SpecSet"]["properties"]
    return {
        key: entry
        for key, entry in vocab.items()
        if key not in spec_set and set(entry.get("scopes", [])) <= {"cell", "state"}
    }


def build() -> str:
    props = json.loads((MAPPINGS / "property_map.curated.json").read_text(encoding="utf-8"))["mappings"]
    units = json.loads((MAPPINGS / "unit_map.curated.json").read_text(encoding="utf-8"))["mappings"]
    parameter_only = parameter_only_keys()
    by_key = {p["key"]: p for p in props}
    props = [p for p in props if p["key"] not in parameter_only]

    lines = [
        "# Properties and units",
        "",
        "<!-- GENERATED by scripts/gen_property_reference.py — do not edit.",
        "     Regenerate with `uv run python scripts/gen_property_reference.py`. -->",
        "",
        'Every quantity you author — `{"value": 5.0, "unit": "Ah"}` under a',
        "`properties` key — is mapped to an EMMO class, and every unit symbol to a",
        "unit IRI, by the curated mapping tables under",
        "`assets/mappings/domain-battery/` — the single source of truth for the",
        "semantics of emitted JSON-LD. This page is generated from those tables.",
        "",
        f"## Properties ({len(props)})",
        "",
        "The keys of quantities in `properties={...}` on a cell spec and in the",
        "`property` blocks of material and component records, and the EMMO class",
        "each becomes in JSON-LD:",
        "",
        "| Key | EMMO class |",
        "|---|---|",
    ]
    for p in sorted(props, key=lambda p: p["key"]):
        lines.append(f"| `{p['key']}` | [{p['class_pref_label']}]({p['class_iri']}) |")

    lines += [
        "",
        f"## Parameter-set keys ({len(parameter_only)})",
        "",
        "Keys for parameter-set claims about a whole cell or its state, most of",
        "them the Cell and State values of a BPX file, which stay on the file's",
        "parameter-set record. A cell spec does not accept them as properties. A",
        "key with no EMMO class yet is typed by its value basis alone, and",
        "validation warns `semantic.property_unmapped`.",
        "",
        "| Key | Unit | EMMO class |",
        "|---|---|---|",
    ]
    for key in sorted(parameter_only):
        mapped = by_key.get(key)
        cls = f"[{mapped['class_pref_label']}]({mapped['class_iri']})" if mapped else "none yet"
        lines.append(f"| `{key}` | `{parameter_only[key].get('unit', '1')}` | {cls} |")

    lines += [
        "",
        f"## Units ({len(units)})",
        "",
        "The unit symbols accepted in quantity dicts, and the unit IRI each maps",
        "to (EMMO where a term exists, QUDT as the documented fallback):",
        "",
        "| Symbol | Unit |",
        "|---|---|",
    ]
    for u in sorted(units, key=lambda u: u["symbol"].lower()):
        lines.append(f"| `{u['symbol']}` | [{u['unit_pref_label']}]({u['unit_iri']}) |")

    entity_map = json.loads((MAPPINGS / "entity_type_map.json").read_text(encoding="utf-8"))["mappings"]
    chemistry = entity_map["chemistry"]
    context = json.loads(CONTEXT.read_text(encoding="utf-8"))
    context = context.get("@context", context)

    def class_link(name: str) -> str:
        term = context.get(name)
        iri = term.get("@id") if isinstance(term, dict) else term
        return f"[{name}]({iri})" if isinstance(iri, str) else name

    canonical = {k: v for k, v in chemistry.items() if "alias_of" not in v}
    aliases = {k: v for k, v in chemistry.items() if "alias_of" in v}

    def code_list(labels: list[str]) -> str:
        quoted = [f"`{label}`" for label in labels]
        return quoted[0] if len(quoted) == 1 else f"{', '.join(quoted[:-1])} and {quoted[-1]}"

    defined_by_negative: dict[str, list[str]] = {}
    for key, entry in canonical.items():
        if entry.get("negative_electrode_basis"):
            defined_by_negative.setdefault(entry["negative_electrode_basis"], []).append(key)
    lines += [
        "",
        f"## Chemistry labels ({len(canonical)})",
        "",
        "The recognised values of `chemistry` on a cell spec. A label names the",
        "electrochemical couple and nothing else. Whether the cell is rechargeable",
        "goes in `rechargeable`, and the electrode materials of a Li-ion cell go",
        "in `positive_electrode_basis` and `negative_electrode_basis`.",
        "",
        "Some labels are narrower than others: a `li-mno2` cell is also a",
        "`li-metal` cell. State the narrowest one you know. Matching ignores case,",
        "so `Li-ion` and `li-ion` are the same label. A value that is not listed is",
        "kept as plain text and the record gets no battery class from it.",
        "",
        "The chemistry decides the battery classes. An electrode basis adds its",
        "class only where the class fits the chemistry: `graphite`, `lto` and the",
        "lithium-ion positives add theirs to a `li-ion` cell, a lithium negative",
        "adds LithiumMetalBattery to `li-metal` and the labels under it, and `mno2`",
        "adds LithiumManganeseDioxideBattery to `li-mno2` and `li-metal`. So an",
        "alkaline cell with an MnO2 positive stays an alkaline zinc cell, and a",
        "chemistry that is not listed gets no class from its electrodes either.",
        "",
        *textwrap.wrap(
            "Some couples are defined by their negative electrode: "
            + "; ".join(
                f"{code_list(labels)} and the labels under {'it' if len(labels) == 1 else 'them'} "
                f"have a {basis} negative"
                for basis, labels in defined_by_negative.items()
            )
            + ". A full cell with one of those negatives needs one of those chemistries. Validation "
            "reports a record that breaks either rule as `semantic.chemistry_electrode_conflict`, an "
            "error under the strict and publisher policies. A half cell or a three-electrode cell may "
            "use lithium as its counter electrode under any chemistry.",
            width=74,
        ),
        "",
        "| Label | Narrower than | Battery class |",
        "|---|---|---|",
    ]
    for key, entry in canonical.items():
        broader = f"`{entry['broader']}`" if entry.get("broader") else ""
        classes = ", ".join(class_link(name) for name in entry["battery_types"])
        lines.append(f"| `{key}` | {broader} | {classes} |")
    lines += [
        "",
        "Older spellings that still resolve. Validation flags them with the label",
        "to use instead:",
        "",
        "| Older label | Use | Why |",
        "|---|---|---|",
    ]
    for key, entry in aliases.items():
        lines.append(f"| `{key}` | `{entry['alias_of']}` | {entry['note']} |")

    lines += [
        "",
        "Unknown keys and symbols are refused, not guessed — see the",
        "[validation contract](../guarantees.md#validation-contract) for how mapping gaps",
        "surface as machine-readable issues.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
